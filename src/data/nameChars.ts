// ─── 성별 필터 ─────────────────────────────────────────────────────────────
export function getCharsByGender(gender: 'male' | 'female'): NameCharData[] {
  return NAME_CHARS.filter(
    c => (c.gender === gender || c.gender === 'neutral') &&
         c.hangul !== '윤2' // 중복 제거
  );
}

// ─── 돌림자/이름 글자 검색 ──────────────────────────────────────────────────
export function findDolrimChar(hangul: string): NameCharData | undefined {
  return NAME_CHARS.find(c => c.hangul === hangul);
}

export function findCharByHangul(hangul: string): NameCharData | undefined {
  return NAME_CHARS.find(c => c.hangul === hangul);
}

