// 오음론(五音論) 초성→오행
// 아음 ㄱ,ㅋ → 목 / 설음 ㄴ,ㄷ,ㄹ,ㅌ → 화 / 순음 ㅁ,ㅂ,ㅍ → 수 / 치음 ㅅ,ㅈ,ㅊ → 금 / 후음 ㅇ,ㅎ → 토

function c(
  hangul: string,
  hanja: string,
  meaning: string,
  ohaeng: OhaengType,
  yinyang: '양' | '음',
  gender: 'male' | 'female' | 'neutral',
  modernity: number,       // 2020-2024 한국 출생신고 기반 선호도 0-100
  positivity: number,      // 의미 긍정성 0-100
  nameStyleFit: NameStyle[],
  images: ImageType[],
): NameCharData {
  return { hangul, hanja, meaning, ohaeng, yinyang, gender, modernity, positivity, nameStyleFit, images };
}

